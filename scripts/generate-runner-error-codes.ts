// `node scripts/generate-runner-error-codes.ts [--write]` — renders the Swift runner's two
// error-code enums from the declarations in packages/apple-runner/src/runner-contract.ts.
//
// `RUNNER_ERROR_CODES` becomes `RunnerWireErrorCode` and `RUNNER_PASS_THROUGH_CODES` becomes
// `RunnerPassThroughErrorCode`: one `static let` per code, named as the code in lowerCamelCase.
// Without `--write` the script compares the file on disk against the rendered one and fails when
// they differ, which is what the `runner-error-codes` gate runs.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { RUNNER_ERROR_CODES, RUNNER_PASS_THROUGH_CODES } from '@agent-device/apple-runner';

const REPO_ROOT = path.resolve(import.meta.dirname, '..');
export const GENERATED_SWIFT_FILE = 'RunnerErrorCodes.swift';
const SWIFT_PATH = path.join(
  'apple/runner/AgentDeviceRunner/AgentDeviceRunnerUITests',
  GENERATED_SWIFT_FILE,
);

export const RUNNER_CODE_ENUMS = {
  RunnerWireErrorCode: Object.keys(RUNNER_ERROR_CODES),
  RunnerPassThroughErrorCode: [...RUNNER_PASS_THROUGH_CODES],
} as const satisfies Record<string, readonly string[]>;

/** `RUNNER_BUSY` is emitted as `runnerBusy`. */
export function swiftConstantName(code: string): string {
  return code.toLowerCase().replaceAll(/_([a-z0-9])/g, (_, first: string) => first.toUpperCase());
}

function renderEnum(name: string, codes: readonly string[]): string {
  const constants = codes.map((code) => `    static let ${swiftConstantName(code)} = "${code}"`);
  return `  enum ${name} {\n${constants.join('\n')}\n  }`;
}

function renderSwift(): string {
  const duplicates = Object.values(RUNNER_CODE_ENUMS)
    .flat()
    .filter((code, index, all) => all.indexOf(code) !== index);
  if (duplicates.length > 0) {
    throw new Error(`Declared as both a table row and a pass-through code: ${duplicates.join()}`);
  }
  const enums = Object.entries(RUNNER_CODE_ENUMS).map(([name, codes]) => renderEnum(name, codes));
  return `// Generated by \`pnpm generate:runner-error-codes\`. Do not edit this file.
// To add, rename or remove a code, edit RUNNER_ERROR_CODES (a code the daemon classifies) or
// RUNNER_PASS_THROUGH_CODES (a code it publishes verbatim) in
// packages/apple-runner/src/runner-contract.ts, then run the generator.

extension RunnerTests {
${enums.join('\n\n')}
}
`;
}

function main(argv: readonly string[]): number {
  const target = path.join(REPO_ROOT, SWIFT_PATH);
  const committed = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  const generated = renderSwift();
  if (committed === generated) {
    process.stdout.write(`${SWIFT_PATH} is current.\n`);
    return 0;
  }
  if (!argv.includes('--write')) {
    process.stderr.write(`${SWIFT_PATH} is stale. Run \`pnpm generate:runner-error-codes\`.\n`);
    return 1;
  }
  fs.writeFileSync(target, generated);
  process.stdout.write(`Wrote ${SWIFT_PATH}.\n`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exit(main(process.argv.slice(2)));
}
