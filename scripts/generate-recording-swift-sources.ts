// Writes packages/capture-kit/src/recording/recording-swift-sources.ts from the recording helper sources, so the
// overlay and the frame decoder compile bytes shipped inside the JavaScript build, never a file found on disk.
// recording-swift-sources.test.ts fails when the generated module and the .swift files differ.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const scriptsDir = path.join(repoRoot, 'apple/runner/AgentDeviceRunner/RecordingScripts');
const output = path.join(repoRoot, 'packages/capture-kit/src/recording/recording-swift-sources.ts');

const read = (fileName: string) =>
  JSON.stringify(fs.readFileSync(path.join(scriptsDir, fileName), 'utf8'));

fs.writeFileSync(
  output,
  `// Generated by \`pnpm generate:recording-swift-sources\` from apple/runner/AgentDeviceRunner/RecordingScripts.
// Do not edit: recording-swift-sources.test.ts fails when this file and the .swift sources differ.
import type { EmbeddedSwiftSource } from './swift-cache.ts';

const RECORDING_EXPORT_SUPPORT: EmbeddedSwiftSource = {
  fileName: 'RecordingExportSupport.swift',
  text: ${read('RecordingExportSupport.swift')},
};

/** The touch-overlay helper: its main file first, then the shared export support. */
export const RECORDING_OVERLAY_SOURCES: readonly EmbeddedSwiftSource[] = [
  { fileName: 'recording-overlay.swift', text: ${read('recording-overlay.swift')} },
  RECORDING_EXPORT_SUPPORT,
];

/** The contact-sheet frame decoder: its main file first, then the shared export support. */
export const RECORDING_FRAMES_SOURCES: readonly EmbeddedSwiftSource[] = [
  { fileName: 'recording-frames.swift', text: ${read('recording-frames.swift')} },
  RECORDING_EXPORT_SUPPORT,
];
`,
);
// Written in the repository's format, so a regeneration leaves nothing for `pnpm format` to change.
execFileSync(
  process.execPath,
  [path.join(repoRoot, 'node_modules/oxfmt/bin/oxfmt'), '--write', output],
  {
    stdio: 'inherit',
  },
);
