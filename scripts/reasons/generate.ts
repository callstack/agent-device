// `pnpm generate:reasons` — writes `website/docs/docs/error-reasons.md` from every reason table in
// the tracked production sources (see collect.ts), or fails when the collected vocabulary has a
// problem. test/repo-guards/reason-tables.test.ts fails when the committed page is stale.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { listCliCommandNames } from '@agent-device/command-registry/catalog';
import { listTrackedProductionSources } from '../layering/tracked-sources.ts';
import {
  collectReasonTables,
  reasonTableProblems,
  type CollectedReasonRow,
  type CollectedReasonTable,
} from './collect.ts';

const REPO_ROOT = path.resolve(import.meta.dirname, '../..');
export const PAGE_PATH = path.join('website', 'docs', 'docs', 'error-reasons.md');

/** Every reason table in the tracked production sources of `repoRoot`. */
export function collectRepoReasonTables(repoRoot: string = REPO_ROOT): CollectedReasonTable[] {
  const sources = new Map<string, string>();
  for (const file of listTrackedProductionSources(repoRoot)) {
    const absolute = path.join(repoRoot, file);
    if (fs.existsSync(absolute)) sources.set(file, fs.readFileSync(absolute, 'utf8'));
  }
  return collectReasonTables(sources);
}

/**
 * The page: rows grouped under each command they name, or under their table's subsystem, then
 * ordered by table and declaration. A row that names two commands appears under both.
 */
export function renderPage(tables: readonly CollectedReasonTable[]): string {
  const byCommand = new Map<string, CollectedReasonRow[]>();
  const bySubsystem = new Map<string, CollectedReasonRow[]>();
  const add = (groups: Map<string, CollectedReasonRow[]>, key: string, row: CollectedReasonRow) =>
    groups.set(key, [...(groups.get(key) ?? []), row]);
  for (const table of [...tables].sort(byTable)) {
    for (const row of table.rows) {
      if (table.subsystem !== undefined) add(bySubsystem, table.subsystem, row);
      else for (const command of row.commands) add(byCommand, command, row);
    }
  }
  return [
    '---',
    'title: Error reasons',
    'description: Every typed error.details.reason value that agent-device declares in a reason table, grouped by command and subsystem.',
    '---',
    '',
    '<!-- Generated by `pnpm generate:reasons` from the reason tables in the source. Do not edit. -->',
    '',
    'A failed command can name why it failed in `error.details.reason`. Branch on the reason, not on the message: a message can change, and a published reason keeps its spelling.',
    '',
    'Treat a reason that this page does not list as unknown, not as an error in the response: a newer daemon or a provider plugin can add reasons. [Commands](/docs/commands) documents more reasons with the behavior of each command.',
    '',
    '## Commands',
    '',
    ...sections(byCommand, (command) => `\`${command}\``),
    '## Subsystems',
    '',
    'These reasons can come from more than one command.',
    '',
    ...sections(bySubsystem, (subsystem) => subsystem[0]!.toUpperCase() + subsystem.slice(1)),
  ].join('\n');
}

function sections(
  groups: ReadonlyMap<string, readonly CollectedReasonRow[]>,
  heading: (key: string) => string,
): string[] {
  return [...groups.keys()]
    .sort()
    .flatMap((key) => [
      `### ${heading(key)}`,
      '',
      '| Reason | Meaning |',
      '| --- | --- |',
      ...groups
        .get(key)!
        .map((row) => `| \`${row.reason}\` | ${row.summary.replaceAll('|', String.raw`\|`)} |`),
      '',
    ]);
}

function byTable(left: CollectedReasonTable, right: CollectedReasonTable): number {
  return left.file.localeCompare(right.file) || left.line - right.line;
}

function main(): number {
  const tables = collectRepoReasonTables();
  const problems = reasonTableProblems(tables, new Set(listCliCommandNames()));
  if (problems.length > 0) {
    process.stderr.write(`${problems.join('\n')}\n`);
    return 1;
  }
  fs.writeFileSync(path.join(REPO_ROOT, PAGE_PATH), renderPage(tables));
  process.stdout.write(`Wrote ${PAGE_PATH}.\n`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exit(main());
}
